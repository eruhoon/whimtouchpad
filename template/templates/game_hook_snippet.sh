#!/bin/bash
# ==============================================================================
# WhimPad Game Launcher Hook Snippet
# ==============================================================================
# PortMaster 게임 실행 스크립트(/roms/ports/<GameName>.sh)에 아래 스니펫을 추가하십시오.
# ==============================================================================

# ------------------------------------------------------------------------------
# 1단계: 게임 바이너리 실행 직전 삽입 (WhimPad 오버레이 시작)
# ------------------------------------------------------------------------------
WHIMPAD_DIR="/roms/ports/whimpad"
# 기기 마운트 위치 자동 탐색 (기본 /roms/ports, 보조 /roms2/ports 또는 스크립트 상대경로)
if [ ! -d "$WHIMPAD_DIR" ]; then
  if [ -d "/roms2/ports/whimpad" ]; then
    WHIMPAD_DIR="/roms2/ports/whimpad"
  elif [ -d "$(dirname "$0")/whimpad" ]; then
    WHIMPAD_DIR="$(dirname "$0")/whimpad"
  fi
fi

if [ -f "$WHIMPAD_DIR/whim_hook.sh" ]; then
  source "$WHIMPAD_DIR/whim_hook.sh"
fi

# ------------------------------------------------------------------------------
# [기존 게임 실행 명령 위치]
# $GAMEDIR/game.bin "$@"
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
# 2단계: 게임 종료 직후 (exit 0 바로 윗줄) 삽입 (WhimPad 오버레이 정리 및 보조화면 절전)
# ------------------------------------------------------------------------------
if [ -f "$WHIMPAD_DIR/whim_cleanup.sh" ]; then
  source "$WHIMPAD_DIR/whim_cleanup.sh"
fi
